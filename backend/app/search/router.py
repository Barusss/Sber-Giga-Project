"""Reusable retrieval layer: OCR chunks, facts, provenance, lexical + vector search.

Embeddings are deliberately generated by caller modules so the API doesn't
silently use the wrong model. PostgreSQL runs pgvector; SQLite supports only
lexical search (useful for development and unit tests).
"""
import json
import re

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import func, or_, select, text
from sqlalchemy.orm import Session, selectinload

from app.core.db import get_db
from app.core.models import Chunk, ChunkSource, Document, Fact, FactEvidence, Fragment, Project, ReviewState
from app.core.schemas import (
    ChunkOut, ChunkSourceOut, EmbeddingUpdate, FactCreate, FactEvidenceOut,
    FactOut, SearchHit, SearchInput,
)

router = APIRouter(tags=["retrieval"])

# Extensible vocabulary, not separate tables for each new type.
FACT_TYPES = {
    "power_limit": "Ограничение или максимальная мощность",
    "connection_point": "Точка технологического присоединения",
    "completion_deadline": "Срок выполнения мероприятий",
    "normative_reference": "Ссылка на ГОСТ/НТД",
    "technical_requirement": "Отдельное техническое требование",
}


def require_document(db: Session, document_id: str) -> Document:
    document = db.get(Document, document_id)
    if document is None:
        raise HTTPException(404, "Document not found")
    return document


def writable(db: Session, document: Document):
    if db.get(Project, document.project_id).state == ReviewState.approved:
        raise HTTPException(409, "Approved project cannot be modified")


def chunk_out(chunk: Chunk) -> ChunkOut:
    return ChunkOut(
        id=chunk.id, document_id=chunk.document_id, position=chunk.position,
        page_start=chunk.page_start, page_end=chunk.page_end,
        section_path=chunk.section_path, text=chunk.text,
        embedding_model=chunk.embedding_model,
        sources=[ChunkSourceOut(
            fragment_id=source.fragment_id, page=source.fragment.page,
            start_offset=source.start_offset, end_offset=source.end_offset,
            bbox=source.fragment.bbox,
        ) for source in chunk.sources],
    )


def fact_out(fact: Fact) -> FactOut:
    return FactOut(
        id=fact.id, document_id=fact.document_id, fact_type=fact.fact_type,
        value=fact.value, confidence=fact.confidence,
        extraction_version=fact.extraction_version,
        review_status=fact.review_status, created_at=fact.created_at,
        evidence=[FactEvidenceOut(
            fragment_id=e.fragment_id, document_id=e.fragment.document_id,
            page=e.fragment.page, quote=e.quote,
        ) for e in fact.evidence],
    )


@router.get("/fact-types")
def fact_types():
    return FACT_TYPES


@router.get("/documents/{document_id}/chunks", response_model=list[ChunkOut])
def list_chunks(document_id: str, limit: int = 100, offset: int = 0, db: Session = Depends(get_db)):
    require_document(db, document_id)
    if not (1 <= limit <= 500 and offset >= 0):
        raise HTTPException(422, "Limit must be 1..500 and offset >= 0")
    chunks = db.scalars(
        select(Chunk).where(Chunk.document_id == document_id).order_by(Chunk.position)
        .limit(limit).offset(offset)
        .options(selectinload(Chunk.sources).selectinload(ChunkSource.fragment))
    ).all()
    return [chunk_out(chunk) for chunk in chunks]


@router.get("/documents/{document_id}/facts", response_model=list[FactOut])
def list_facts(document_id: str, fact_type: str | None = None, db: Session = Depends(get_db)):
    require_document(db, document_id)
    stmt = select(Fact).where(Fact.document_id == document_id)
    if fact_type:
        stmt = stmt.where(Fact.fact_type == fact_type)
    facts = db.scalars(stmt.order_by(Fact.created_at, Fact.id).options(
        selectinload(Fact.evidence).selectinload(FactEvidence.fragment)
    )).all()
    return [fact_out(fact) for fact in facts]


@router.post("/documents/{document_id}/facts", response_model=FactOut, status_code=201)
def create_fact(document_id: str, payload: FactCreate, db: Session = Depends(get_db)):
    doc = require_document(db, document_id)
    writable(db, doc)
    fragment_ids = [e.fragment_id for e in payload.evidence]
    fragments = {f.id: f for f in db.scalars(select(Fragment).where(Fragment.id.in_(fragment_ids))).all()}
    for evidence in payload.evidence:
        fragment = fragments.get(evidence.fragment_id)
        if not fragment or fragment.document_id != document_id:
            raise HTTPException(422, "Evidence fragment must belong to the document")
        # Prevent unsupported invented quotations; normalize whitespace only.
        if " ".join(evidence.quote.split()).casefold() not in " ".join(fragment.text.split()).casefold():
            raise HTTPException(422, "Evidence quote does not occur in its fragment")
    fact = Fact(document_id=document_id, fact_type=payload.fact_type, value=payload.value,
                confidence=payload.confidence, extraction_version=payload.extraction_version)
    db.add(fact)
    db.flush()
    for item in payload.evidence:
        db.add(FactEvidence(fact_id=fact.id, fragment_id=item.fragment_id, quote=item.quote))
    db.commit()
    # Re-load relationships: tests use fresh response, no accidental lazy-load in serializers.
    fact = db.scalar(select(Fact).where(Fact.id == fact.id).options(
        selectinload(Fact.evidence).selectinload(FactEvidence.fragment)))
    return fact_out(fact)


@router.put("/documents/{document_id}/chunks/{chunk_id}/embedding", response_model=ChunkOut)
def set_chunk_embedding(document_id: str, chunk_id: str, payload: EmbeddingUpdate, db: Session = Depends(get_db)):
    doc = require_document(db, document_id)
    writable(db, doc)
    if db.bind.dialect.name != "postgresql":
        raise HTTPException(501, "Vector storage requires PostgreSQL with pgvector")
    chunk = db.scalar(select(Chunk).where(Chunk.id == chunk_id, Chunk.document_id == document_id))
    if chunk is None:
        raise HTTPException(404, "Chunk not found")
    # Explicit cast avoids psycopg type inference differences for pgvector.
    db.execute(text("""
        UPDATE chunks SET embedding = CAST(:vector AS vector), embedding_model = :model
        WHERE id = :id AND document_id = :document_id
    """), {"vector": json.dumps(payload.embedding, separators=(",", ":")),
           "model": payload.embedding_model, "id": chunk_id, "document_id": document_id})
    db.commit()
    chunk = db.scalar(select(Chunk).where(Chunk.id == chunk_id).options(
        selectinload(Chunk.sources).selectinload(ChunkSource.fragment)))
    return chunk_out(chunk)


def lexical_ids(db: Session, document_id: str, query: str, max_results: int) -> list[str]:
    if db.bind.dialect.name == "postgresql":
        tsv = func.to_tsvector("russian", Chunk.text)
        tsq = func.plainto_tsquery("russian", query)
        # ILIKE covers technical identifiers, which Russian stemming may miss.
        escaped = query.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
        rows = db.scalars(
            select(Chunk.id).where(Chunk.document_id == document_id).where(
                or_(tsv.op("@@")(tsq), Chunk.text.ilike(f"%{escaped}%", escape="\\")))
            .order_by(func.ts_rank(tsv, tsq).desc(), Chunk.position).limit(max_results)
        ).all()
    else:
        words = [w for w in re.findall(r"[\w-]+", query.lower()) if len(w) > 1][:12]
        if not words:
            return []
        rows = db.scalars(
            select(Chunk.id).where(Chunk.document_id == document_id).where(
                or_(*(func.lower(Chunk.text).contains(w) for w in words)))
            .order_by(Chunk.position).limit(max_results)
        ).all()
    return list(rows)


def semantic_ids(db: Session, document_id: str, embedding_model: str, embedding: list[float], max_results: int) -> list[str]:
    # Parameterized pgvector query; no untrusted strings interpolated into SQL.
    vector_text = json.dumps(embedding, separators=(",", ":"))
    return list(db.scalars(text("""
        SELECT id FROM chunks
        WHERE document_id = :document_id
          AND embedding_model = :model AND embedding IS NOT NULL
        ORDER BY embedding <=> CAST(:vector AS vector)
        LIMIT :n
    """), {"document_id": document_id, "model": embedding_model,
           "vector": vector_text, "n": max_results}).all())


@router.post("/documents/{document_id}/search", response_model=list[SearchHit])
def search_chunks(document_id: str, payload: SearchInput, db: Session = Depends(get_db)):
    require_document(db, document_id)
    if payload.embedding is not None and db.bind.dialect.name != "postgresql":
        raise HTTPException(501, "Semantic retrieval requires PostgreSQL with pgvector")
    top = min(payload.limit * 5, 100)
    ranked: dict[str, dict] = {}
    channels = []
    if payload.query and payload.query.strip():
        channels.append(("lexical", lexical_ids(db, document_id, payload.query.strip(), top)))
    if payload.embedding is not None:
        channels.append(("semantic", semantic_ids(db, document_id, payload.embedding_model, payload.embedding, top)))
    for channel, ids in channels:
        for rank, chunk_id in enumerate(ids, start=1):
            value = ranked.setdefault(chunk_id, {"score": 0.0, "channels": []})
            value["score"] += 1.0 / (60 + rank)  # Reciprocal rank fusion
            value["channels"].append(channel)
    if not ranked:
        return []
    top_ids = sorted(ranked, key=lambda k: (-ranked[k]["score"], k))[:payload.limit]
    chunks = db.scalars(select(Chunk).where(Chunk.id.in_(top_ids)).options(
        selectinload(Chunk.sources).selectinload(ChunkSource.fragment))).all()
    by_id = {c.id: c for c in chunks}
    return [SearchHit(chunk=chunk_out(by_id[chunk_id]), **ranked[chunk_id]) for chunk_id in top_ids]
